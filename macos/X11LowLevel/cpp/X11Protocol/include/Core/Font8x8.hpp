#pragma once
#include <cstdint>

namespace x11 {

// 8x8 glyphs for ASCII 32..127. For bring-up we include only a subset.
// Missing glyphs render as '?'.
struct Glyph8x8 { uint8_t row[8]; };

// Very small minimal font table (add more as needed).
inline const Glyph8x8& glyph8x8(uint8_t ch) {
  static const Glyph8x8 qmark {{0x3C,0x42,0x02,0x0C,0x10,0x00,0x10,0x00}};
  static const Glyph8x8 space {{0,0,0,0,0,0,0,0}};
  // digits '0'..'9'
  static const Glyph8x8 dig[10] = {
    {{0x3C,0x42,0x46,0x4A,0x52,0x62,0x42,0x3C}}, // 0
    {{0x08,0x18,0x28,0x08,0x08,0x08,0x08,0x3E}}, // 1
    {{0x3C,0x42,0x02,0x0C,0x30,0x40,0x40,0x7E}}, // 2
    {{0x3C,0x42,0x02,0x1C,0x02,0x02,0x42,0x3C}}, // 3
    {{0x04,0x0C,0x14,0x24,0x44,0x7E,0x04,0x04}}, // 4
    {{0x7E,0x40,0x40,0x7C,0x02,0x02,0x42,0x3C}}, // 5
    {{0x1C,0x20,0x40,0x7C,0x42,0x42,0x42,0x3C}}, // 6
    {{0x7E,0x02,0x04,0x08,0x10,0x20,0x20,0x20}}, // 7
    {{0x3C,0x42,0x42,0x3C,0x42,0x42,0x42,0x3C}}, // 8
    {{0x3C,0x42,0x42,0x42,0x3E,0x02,0x04,0x38}}, // 9
  };
  // letters 'a'..'z' (lowercase only; xterm will still show something)
  static const Glyph8x8 low[26] = {
    {{0x00,0x00,0x3C,0x02,0x3E,0x42,0x46,0x3A}}, // a
    {{0x40,0x40,0x5C,0x62,0x42,0x42,0x62,0x5C}}, // b
    {{0x00,0x00,0x3C,0x42,0x40,0x40,0x42,0x3C}}, // c
    {{0x02,0x02,0x3A,0x46,0x42,0x42,0x46,0x3A}}, // d
    {{0x00,0x00,0x3C,0x42,0x7E,0x40,0x42,0x3C}}, // e
    {{0x0C,0x12,0x10,0x3C,0x10,0x10,0x10,0x10}}, // f
    {{0x00,0x00,0x3A,0x46,0x42,0x3E,0x02,0x3C}}, // g
    {{0x40,0x40,0x5C,0x62,0x42,0x42,0x42,0x42}}, // h
    {{0x08,0x00,0x18,0x08,0x08,0x08,0x08,0x1C}}, // i
    {{0x04,0x00,0x0C,0x04,0x04,0x04,0x44,0x38}}, // j
    {{0x40,0x40,0x44,0x48,0x70,0x48,0x44,0x42}}, // k
    {{0x18,0x08,0x08,0x08,0x08,0x08,0x08,0x1C}}, // l
    {{0x00,0x00,0x6C,0x52,0x52,0x52,0x52,0x52}}, // m
    {{0x00,0x00,0x5C,0x62,0x42,0x42,0x42,0x42}}, // n
    {{0x00,0x00,0x3C,0x42,0x42,0x42,0x42,0x3C}}, // o
    {{0x00,0x00,0x5C,0x62,0x42,0x62,0x5C,0x40}}, // p
    {{0x00,0x00,0x3A,0x46,0x42,0x46,0x3A,0x02}}, // q
    {{0x00,0x00,0x5C,0x62,0x40,0x40,0x40,0x40}}, // r
    {{0x00,0x00,0x3E,0x40,0x3C,0x02,0x42,0x3C}}, // s
    {{0x10,0x10,0x3C,0x10,0x10,0x10,0x12,0x0C}}, // t
    {{0x00,0x00,0x42,0x42,0x42,0x42,0x46,0x3A}}, // u
    {{0x00,0x00,0x42,0x42,0x42,0x24,0x24,0x18}}, // v
    {{0x00,0x00,0x42,0x42,0x52,0x52,0x52,0x2C}}, // w
    {{0x00,0x00,0x42,0x24,0x18,0x18,0x24,0x42}}, // x
    {{0x00,0x00,0x42,0x42,0x46,0x3A,0x02,0x3C}}, // y
    {{0x00,0x00,0x7E,0x04,0x18,0x20,0x40,0x7E}}, // z
  };

  if (ch == ' ') return space;
  if (ch >= '0' && ch <= '9') return dig[ch - '0'];
  if (ch >= 'a' && ch <= 'z') return low[ch - 'a'];
  return qmark;
}

} // namespace x11
